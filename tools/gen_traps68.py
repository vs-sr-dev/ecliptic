"""Generate src/traps68_table.inc (68k system trap and TwDispatch selector names) from the SDK
headers CoreTraps.h and TapWave/TwTraps.h. Names only, used for logging."""
import re
INC = 'ref/sdk11/Tapwave 1.1 SDK/Incs/'
out = ['// Generated by tools/gen_traps68.py from CoreTraps.h and TwTraps.h. Do not edit.']
seen = set()
for line in open(INC + 'CoreTraps.h', encoding='latin1'):
    m = re.match(r'#define\s+sysTrap(\w+)\s+0x([0-9A-Fa-f]{4})\b', line)
    if m and m.group(2).upper() not in seen:
        seen.add(m.group(2).upper())
        out.append(f'TRAPNAME(0x{m.group(2).upper()}, "{m.group(1)}")')
for line in open(INC + 'TapWave/TwTraps.h', encoding='latin1'):
    m = re.match(r'#define\s+trap(Tw\w+|\w+)\s+(\d+)\b', line)
    if m:
        out.append(f'TWSELNAME({m.group(2)}, "{m.group(1)}")')
open('src/traps68_table.inc', 'w').write('\n'.join(out) + '\n')
print(len(out) - 1, 'entries')
