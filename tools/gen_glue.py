"""Generate src/glue_table.inc from the Tapwave 1.1 SDK TwGlue.h (struct TwGlue)."""
import re
H = 'ref/sdk11/Tapwave 1.1 SDK/Incs/TapWave/TwGlue.h'
src = open(H, encoding='latin1').read().replace('\r', '')
body = src[src.index('struct TwGlue\n{'):]
body = body[:body.index('\n};')]
out = []
for line in body.split('\n'):
    s = line.strip()
    if not s.startswith(('#', '//')) and '(*' in s:
        m = re.match(r'(.*?)\(\*([A-Za-z0-9_]+)\)\s*\((.*)\)\s*;\s*$', s)
        assert m, s
        ret, name, args = m.group(1).strip(), m.group(2), m.group(3).strip()
        assert name.endswith('_'), name
        # split top-level commas
        depth, cur, parts = 0, '', []
        for c in args:
            if c == '(': depth += 1
            if c == ')': depth -= 1
            if c == ',' and depth == 0: parts.append(cur); cur = ''
            else: cur += c
        if cur.strip(): parts.append(cur)
        if len(parts) == 1 and parts[0].strip() in ('void', ''): parts = []
        variadic = any(p.strip() == '...' for p in parts)
        nargs = len([p for p in parts if p.strip() != '...'])
        proto = f"{ret} {name[:-1]}({', '.join(p.strip() for p in parts)})"
        out.append((name[:-1], nargs, variadic, ret, proto))
with open('src/glue_table.inc', 'w') as f:
    f.write('// Generated by tools/gen_glue.py from TwGlue.h (Tapwave 1.1 SDK). Do not edit.\n')
    for n, a, v, r, p in out:
        rv = 'void' if r == 'void' else 'val'
        f.write(f'GLUE({n}, {a}, {int(v)}, "{rv}", "{p}")\n')
print(len(out), 'entries')
