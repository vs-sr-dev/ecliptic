"""Map every TwGlue slot to its target in the real 1.1 ROM.

The Tapwave Application Layer (TAL) fills the TwGlue table at runtime, in one function that
stores a pc-relative address into each of the 612 slots. This script evaluates that function
statically and classifies each target:
  - an r9 stub "ldr ip, [r9, #-4*m]; ldr pc, [ip, #4*n]": module m (DAL, Boot, UI, TAL) index n
  - a lazy library stub "ldr ip, [r9]; ldr ip, [ip, #0xc]; ldr ip, [ip, #G]; cmp ip, #0;
    addne pc, ip, #off": entry off / 4 of the jump table that TAL global G points to
  - otherwise a function inside TAL itself
Writes docs/twglue-rom-map.tsv and src/r9_map.inc. Usage: gen_r9map.py [ROM]"""
import struct, sys
from capstone import Cs, CS_ARCH_ARM, CS_MODE_ARM
from capstone.arm import ARM_OP_IMM, ARM_OP_MEM, ARM_OP_REG, ARM_REG_PC, ARM_REG_SP, ARM_REG_IP

ROM = sys.argv[1] if len(sys.argv) > 1 else 'ref/roms/zodiac_1.1.rom'
FILL_END = 0x201F92C8   # tail of the fill function (str r1, [r0, #0x98c] is the last slot)
B = 0x20000000
r = open(ROM, 'rb').read()
md = Cs(CS_ARCH_ARM, CS_MODE_ARM)
md.detail = True
names = [l.strip().rstrip('_') for l in open('tools/twglue_names.txt')]
MODULES = {4: 'DAL', 8: 'Boot', 12: 'UI', 16: 'TAL'}
LIBS = {0x10: 'BtLib', 0x30: 'Zlib', 0x38: 'JPEG', 0x40: 'Midi', 0x48: 'TwMp'}


def w32(a): return struct.unpack_from('<I', r, a - B)[0]
def insn(a): return next(md.disasm(r[a - B:a - B + 4], a), None)


# the fill function starts with "push {r3, sb}" (it loads its globals from [[r9]+0xc])
start = FILL_END
while True:
    start -= 4
    x = insn(start)
    if x and x.mnemonic == 'push' and x.op_str.startswith('{r3, sb'): break

regs, slots = {}, {}
for x in md.disasm(r[start - B:FILL_END - B], start):
    m, ops = x.mnemonic, x.operands
    if m == 'ldr' and ops[1].type == ARM_OP_MEM and ops[1].mem.base == ARM_REG_PC:
        regs[ops[0].reg] = w32((x.address + 8 + ops[1].mem.disp) & ~3)
    elif m == 'add' and len(ops) == 3 and ops[1].reg == ARM_REG_PC and ops[2].type == ARM_OP_REG:
        regs[ops[0].reg] = (x.address + 8 + regs.get(ops[2].reg, 0)) & 0xFFFFFFFF
    elif m in ('add', 'sub') and len(ops) == 3 and ops[1].reg == ARM_REG_PC and ops[2].type == ARM_OP_IMM:
        regs[ops[0].reg] = x.address + 8 + (ops[2].imm if m == 'add' else -ops[2].imm)
    elif m == 'str' and ops[1].type == ARM_OP_MEM and ops[1].mem.base != ARM_REG_SP:
        slots[ops[1].mem.disp // 4] = regs.get(ops[0].reg)
assert len(slots) == len(names), (len(slots), len(names))


def r9_stub(t):
    a, b = w32(t), w32(t + 4)
    if a & 0xFFFF0000 == 0xE5190000 and (a & 0xFFF) in MODULES:
        rt = (a >> 12) & 15
        if b & 0xFFFFF000 == 0xE590F000 | (rt << 16): return MODULES[a & 0xFFF], (b & 0xFFF) // 4
    return None


def lazy_stub(t):
    a = [w32(t + 4 * k) for k in range(5)]
    if a[0] == 0xE599C000 and a[1] == 0xE59CC00C and a[2] & 0xFFFFF000 == 0xE59CC000:
        x = insn(t + 16)
        if x and x.mnemonic == 'addne' and x.operands[1].reg == ARM_REG_IP:
            g = a[2] & 0xFFF
            return LIBS.get(g, f"lib@{g:#x}"), x.operands[2].imm // 4
    return None


rows = []
for i, name in enumerate(names):
    t = slots[i]
    s = r9_stub(t)
    if s: rows.append((i, name, t, s[0], s[1])); continue
    s = lazy_stub(t)
    if s: rows.append((i, name, t, 'lib:' + s[0], s[1])); continue
    rows.append((i, name, t, 'TAL fn', -1))

with open('docs/twglue-rom-map.tsv', 'w', newline='\n') as f:
    f.write('# TwGlue slot -> target in the Zodiac 1.1 ROM (generated by tools/gen_r9map.py)\n')
    f.write('slot\tname\trom_addr\ttarget\tindex\n')
    for i, n, t, k, idx in rows:
        f.write(f'{i}\t{n}\t{t:#010x}\t{k}\t{idx if idx >= 0 else ""}\n')

mod_id = {'DAL': 0, 'Boot': 1, 'UI': 2, 'TAL': 3}
with open('src/r9_map.inc', 'w', newline='\n') as f:
    f.write('// Generated by tools/gen_r9map.py from the Zodiac 1.1 ROM. Do not edit.\n')
    f.write('// r9 module index -> the TwGlue slot whose ROM stub jumps straight to it.\n')
    for i, n, t, k, idx in rows:
        if k in mod_id: f.write(f'{{{mod_id[k]}, {idx}, "{n}"}},\n')

count = {}
for row in rows: count[row[3]] = count.get(row[3], 0) + 1
print(f'fill function {start:#x}-{FILL_END:#x}:', ', '.join(f'{k} {v}' for k, v in sorted(count.items())))
